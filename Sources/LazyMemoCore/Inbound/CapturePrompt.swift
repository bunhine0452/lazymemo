import Foundation

/// 빠른 입력 상자의 안내 문구. **열 때마다 다른 것이 나온다.**
///
/// "무엇이든" 한 마디로 고정해 두었더니, 그 자리는 열흘이면 벽지가 된다 —
/// 늘 같은 글자는 읽히지 않고, 읽히지 않는 안내는 없는 것과 같다. 매번
/// 바뀌면 눈이 한 번은 머문다. 그 한 번에 이 상자가 무엇을 할 줄 아는지를
/// 슬쩍 얹는다.
///
/// 그래서 문구는 세 갈래로 섞여 있다.
/// - **재촉** — 지금 머리에 걸린 것을 꺼내게 만드는 말
/// - **본보기** — `내일 3시` 처럼 적어도 알아듣는다는 것을 보여주는 말
/// - **안심** — 닫아도 남고, 사진도 붙는다는 것
///
/// 긴 말은 못 쓴다. 19pt 로 한 줄에 들어가야 하고, 사용자가 첫 글자를 치는
/// 순간 사라질 글이라 읽는 데 반 초를 넘기면 안 된다.
///
/// 맥의 빠른 입력과 폰의 펜이 같은 문구를 쓴다 — 그래서 Core 에 있다.
public enum CapturePrompt {
    public static var all: [String] { [
        L("지금 머리에 걸린 것"),
        L("잊기 전에, 한 줄"),
        L("적어 두고 잊어버리세요"),
        L("생각난 김에"),
        L("손에서 놓기 전에"),
        L("여기 던져 두세요"),
        L("까먹기 딱 좋은 그거"),
        L("반쯤 잊은 그것"),
        L("쓰다 만 문장도 괜찮습니다"),
        L("내일 3시, 라고 적어도 됩니다"),
        L("치과 목요일 두 시"),
        L("치과 언제였지? — 물으면 답합니다"),
        L("다음 주 화요일 회의"),
        L("금요일까지 할 것"),
        L("장 볼 것 세 가지"),
        L("찾을 것이면 그냥 치세요"),
        L("사진은 붙여넣으면 됩니다"),
        L("닫아도 남습니다"),
        L("짧을수록 남습니다"),
        L("오늘 못 한 일"),
        L("다시 안 떠오를 것 같은 말"),
    ] }

    /// 다음에 보일 문구. **방금 본 것은 다시 뽑지 않는다** — 두 번 연속
    /// 같은 말이 나오면 "바뀐다" 는 사실 자체가 전달되지 않는다.
    public static func next(after previous: String?) -> String {
        let pool = all.filter { $0 != previous }
        return pool.randomElement() ?? all[0]
    }
}
