import LazyMemoCore

/// 「서랍」에 무엇이 들어 있는가 — **한 문장으로 정한다.**
///
/// 이 앱은 폴더도 태그도 만들지 않는다 (철학 2 — 시간이 유일한 구조). 서랍은
/// 그 규칙을 어기지 않는다. **분류가 아니라 자리이기 때문이다** — 이름도
/// 없고, 여러 개도 없고, 무엇을 넣을지 사람이 정할 필요도 없다. 책상 위의
/// 종이를 한쪽으로 밀어 두는 것과 같은 일이고, 그 밀어 두기는 이 앱에 이미
/// 있었다 (종이의 「치우기」, 그리고 스스로 물러나는 것 — `Tidy`).
///
/// 없던 것은 **밀어 둔 종이가 어디로 갔는지 보여주는 자리**뿐이었다. ×를
/// 누른 종이는 그 순간 화면에서 사라졌고, 스스로 물러난 종이는 메뉴 안쪽에
/// 「치워 둔 N장」이라는 숫자로만 남았다. 설계문서가 걱정하던 그대로다 —
/// *"목록에서 빠지기만 하면, 사람은 그것을 「정리됐다」가 아니라 「없어졌다」로
/// 읽는다."* 서랍은 그 N장에 **몸을 준다.**
///
/// ## 규칙
///
/// > 서랍에는 **지금 바탕화면에 없는, 날짜 없는 종이**가 들어 있다.
///
/// 셋을 각각 왜 보는지:
///
/// - **날짜가 없다** — 날짜가 붙은 것은 달력이 맡는다 (§7.2). 달력이 맡은 것을
///   서랍에도 두면 같은 메모가 두 자리에 있게 되고, 그러면 사람은 어느 쪽이
///   진짜인지 매번 판단해야 한다.
/// - **밀어 두었다** — 사람이 ×를 눌렀거나(`layout.json` 의 `hidden`), 규칙이
///   물러나게 했거나(`Memo.tidied`). 둘은 까닭이 다르지만 **지금 종이가 눈앞에
///   없다**는 사실은 같고, 사람이 찾을 때 묻는 것도 그 하나다.
/// - **지워지지 않았다** — 휴지통은 D6 이 맡는다. 지운 것이 서랍에 남아 있으면
///   지우기가 지우기가 아니게 된다.
///
/// 뷰 밖의 순수 함수인 이유는 `MonthGridGeometry` 와 같다. 이 규칙이 한 칸
/// 어긋나면 **종이가 어느 자리에도 없는 상태**가 생기는데(바탕화면에도 없고
/// 서랍에도 안 보이는), 그것은 화면을 봐서는 "원래 없었나" 와 구별되지 않는다.
enum DrawerContents {

    /// 이 종이가 서랍에 있는가.
    ///
    /// - Parameter putAway: 사람이 치웠는가 (`layout.json` 의 `hidden`).
    ///   좌표는 파생물이라 `LazyMemoCore` 가 알지 못하므로 바깥에서 받는다.
    static func holds(_ memo: Memo, putAway: Bool) -> Bool {
        guard memo.deleted == nil else { return false }
        guard !memo.isScheduled else { return false }
        return putAway || memo.tidied != nil
    }

    /// 서랍에 들어 있는 것만 골라 낸다. **차례는 건드리지 않는다** — 들어온
    /// 목록이 이미 고정·최근순이고(`MemoService.sorted`), 서랍만 다른 차례로
    /// 늘어놓으면 같은 메모를 두 곳에서 다르게 그리는 일이 된다 (§14.10).
    static func filter(_ memos: [Memo], putAway: (Memo) -> Bool) -> [Memo] {
        memos.filter { holds($0, putAway: putAway($0)) }
    }

    /// 서랍이 스스로를 뭐라고 부르는가. 숫자만 적으면 그것은 배지이지 말이 아니다.
    static func title(count: Int) -> String {
        count == 0 ? "서랍" : "서랍 · \(count)장"
    }

    /// 겹쳐 놓을 수 있는 것보다 많을 때 **몇 장이 가려졌는지.** 없으면 `nil`.
    ///
    /// 무더기는 여덟 장까지만 놓는다 (`DrawerGeometry.visible`). 그 위는 자리가
    /// 없어서 안 그리는 것인데, **조용히 자르면 사람은 그것을 「전부다」로 읽는다** —
    /// 그리고 이 화면에서 가장 비싼 고장이 바로 «종이가 어디에도 없는 것» 이다.
    /// 판형이 스스로 `scrolls` 로 넘침을 셈해 놓고도 화면에서는 아무 말도 하지
    /// 않고 있었다. 여기서 말을 만든다.
    static func overflow(count: Int, shown: Int) -> String? {
        let hidden = count - shown
        guard hidden > 0 else { return nil }
        return "그리고 \(hidden)장 더"
    }

    /// 고른 장이 몇 장인지. **없으면 아무 말도 하지 않는다.**
    ///
    /// 「0장 골랐습니다」는 말이 아니라 빈칸이다. 고르지 않은 사람에게 고르기의
    /// 존재를 알릴 자리는 여기가 아니다 (철학 1 — 완성을 요구하지 않는다).
    static func picked(count: Int) -> String? {
        count > 0 ? "\(count)장 골랐습니다" : nil
    }

    /// **한 번에 더 펼칠 장수.** 「더 보기」를 누르면 이만큼씩 늘어난다.
    ///
    /// 한꺼번에 전부 펼치지 않는 이유는 창이 화면을 넘기 때문이다. 여덟 장씩
    /// 늘리면 늘어난 만큼이 눈에 보이고, 창이 화면 끝에 닿으면 거기서 멈춘다
    /// (`DrawerGeometry.limit(fitting:)`).
    static let page = 8
}
